"""Item 16 stage 0: distribution of the consensus-score components, from consensus_filter --dump-dist.

Input: one dump TSV per sample (columns: dataset, sample, chrom, start, end, n_supporting, bsj_ciriquant,
dist_ciriquant, bsj_dcc, dist_dcc, confidence_score). Only loci that enter the published consensus are used
(confidence_score is not NA).

CIRIquant and DCC distances are reported separately: the CIRIquant coordinate is normally the cluster
representative, so its distance is 0 by construction when it is present.

usage: confidence_structure_stats.py <dump_root> <out_md> <figure_png> [dump_dirname=dump]
  dump_root holds <GSE>/<dump_dirname>/<srr>.tsv (dump_dirname "dump_pre" for the pre-dedup code)
  Files named *_s.tsv are the consensus summaries written beside the dumps; they are not loci and are skipped
  (counting them doubled the pre-dedup table in the first run).
"""
import glob
import os
import sys

import numpy as np
import pandas as pd

root, out_md, fig_png = sys.argv[1:4]
dump_dir = sys.argv[4] if len(sys.argv) > 4 else "dump"
files = [f for f in glob.glob(os.path.join(root, "*", dump_dir, "*.tsv")) if not f.endswith("_s.tsv")]
def _read(f):
    # dataset and sample come from the dump's location (<root>/<GSE>/dump/<srr>.tsv), not from the
    # output path written inside the dump: the output path depends on where the dump was made
    d = pd.read_csv(f, sep="\t", na_values="NA", dtype={"dist_dcc": float})
    d["dataset"] = os.path.basename(os.path.dirname(os.path.dirname(f)))
    d["sample"] = os.path.splitext(os.path.basename(f))[0]
    return d


df = pd.concat([_read(f) for f in files], ignore_index=True)
df = df[df.confidence_score.notna()].copy()
df["has_ciri"] = df.dist_ciriquant.notna()
df["has_dcc"] = df.dist_dcc.notna()
df["two"] = df.has_ciri & df.has_dcc
df["log_mean"] = np.where(df.two,
                          (np.log2(df.bsj_ciriquant.astype(float) + 1) + np.log2(df.bsj_dcc.astype(float) + 1)) / 2,
                          np.log2(np.where(df.has_ciri, df.bsj_ciriquant, df.bsj_dcc).astype(float) + 1))


def dist_bins(d):
    d = d.dropna()
    n = len(d)
    if n == 0:
        return dict(n=0, zero=np.nan, one_three=np.nan, four_ten=np.nan)
    return dict(n=n, zero=(d == 0).mean(), one_three=((d >= 1) & (d <= 3)).mean(), four_ten=((d >= 4) & (d <= 10)).mean())


lines = ["# Consensus confidence score: structure of the agreement term (stage 0, read-only)\n",
         "Generated by audit/confidence_structure_stats.py from consensus_filter --dump-dist, run on scratch copies of",
         "the 15 analysed datasets. Only loci in the published consensus are counted.\n"]

lines.append("## 1. dist_dcc distribution (loci with DCC support)\n")
lines.append("| dataset | loci | dist 0 | dist 1-3 | dist 4-10 |\n|---|---|---|---|---|")
for g, sub in [("ALL", df)] + list(df.groupby("dataset")):
    b = dist_bins(sub.loc[sub.has_dcc, "dist_dcc"])
    lines.append(f"| {g} | {b['n']} | {b['zero']:.3f} | {b['one_three']:.3f} | {b['four_ten']:.3f} |")

lines.append("\n## 1b. dist_ciriquant distribution (reported separately; expected 0 by construction)\n")
b = dist_bins(df.loc[df.has_ciri, "dist_ciriquant"])
lines.append(f"CIRIquant-supported loci: {b['n']}; dist 0 = {b['zero']:.3f}; dist 1-3 = {b['one_three']:.3f}; "
             f"dist 4-10 = {b['four_ten']:.3f}")

lines.append("\n## 2. n_supporting distribution\n")
lines.append("| dataset | loci | n=1 | n=2 |\n|---|---|---|---|")
for g, sub in [("ALL", df)] + list(df.groupby("dataset")):
    n = len(sub)
    lines.append(f"| {g} | {n} | {(sub.n_supporting == 1).mean():.4f} | {(sub.n_supporting == 2).mean():.4f} |")

lines.append("\n## 3. agreement factor f = 1 - dist_dcc/10 (DCC-supported loci)\n")
lines.append("| dataset | loci | mean f | sd f | CV = sd/mean |\n|---|---|---|---|---|")
for g, sub in [("ALL", df)] + list(df.groupby("dataset")):
    f = (1 - sub.loc[sub.has_dcc, "dist_dcc"] / 10.0).dropna()
    if len(f):
        lines.append(f"| {g} | {len(f)} | {f.mean():.4f} | {f.std(ddof=1):.4f} | {f.std(ddof=1) / f.mean():.4f} |")

lines.append("\n## 4. Spearman rho: confidence_score vs the mean log2(bsj+1) term (agreement term removed)\n")
lines.append("| dataset | loci (all) | rho (all) | loci (2 tools) | rho (2 tools) |\n|---|---|---|---|---|")
from scipy.stats import spearmanr  # noqa: E402  (already a pipeline dependency)
for g, sub in [("ALL", df)] + list(df.groupby("dataset")):
    r_all = spearmanr(sub.confidence_score, sub.log_mean).correlation if len(sub) > 2 else np.nan
    s2 = sub[sub.two]
    r_two = spearmanr(s2.confidence_score, s2.log_mean).correlation if len(s2) > 2 else np.nan
    lines.append(f"| {g} | {len(sub)} | {r_all:.4f} | {len(s2)} | {r_two:.4f} |")

# judgement, decided before the numbers were seen (see audit/item16_plan in the review notes)
all_dcc = dist_bins(df.loc[df.has_dcc, "dist_dcc"])
two = df[df.two]
r_two_all = spearmanr(two.confidence_score, two.log_mean).correlation if len(two) > 2 else np.nan
share0 = all_dcc["zero"]
if share0 >= 0.90 and r_two_all >= 0.99:
    verdict = "STRUCTURAL: dist_dcc = 0 in >= 90% of loci and rho >= 0.99; the agreement term is near-constant."
elif share0 < 0.90:
    verdict = "EMPIRICAL: dist_dcc = 0 in < 90% of loci; the agreement term varies, but see rho before reading it as informative."
else:
    verdict = "INTERMEDIATE: reported as measured; no assignment to either side."
lines.append("\n## Judgement (pre-registered rule)\n")
lines.append(f"- dist_dcc = 0 share (DCC-supported loci): {share0:.3f}")
lines.append(f"- rho between confidence_score and the mean log term (2-tool loci): {r_two_all:.4f}")
lines.append(f"- {verdict}")

open(out_md, "w", encoding="utf-8").write("\n".join(lines) + "\n")

# figure: confidence_score per dataset (one panel each), same colour family as the biomarker score histogram
import matplotlib  # noqa: E402
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
gs = sorted(df.dataset.unique())
ncol = 4
nrow = int(np.ceil(len(gs) / ncol))
fig, axes = plt.subplots(nrow, ncol, figsize=(4 * ncol, 2.8 * nrow), squeeze=False)
for ax, g in zip(axes.ravel(), gs):
    ax.hist(df.loc[df.dataset == g, "confidence_score"], bins=40, color="#4C72B0")
    ax.set_title(g, fontsize=9)
    ax.set_xlabel("confidence_score", fontsize=8)
    ax.set_ylabel("loci", fontsize=8)
for ax in axes.ravel()[len(gs):]:
    ax.axis("off")
fig.tight_layout()
fig.savefig(fig_png, dpi=110)
print("wrote", out_md, fig_png, "loci:", len(df))
